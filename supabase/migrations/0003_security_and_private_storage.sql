-- Security hardening and private Storage bucket setup.
-- Supabase service_role bypasses RLS; keep its key exclusively in backend env vars.

-- End users must not be able to approve community material or verify lawyer accounts.
drop policy if exists community_posts_owner_update on public.community_posts;
drop policy if exists community_comments_owner_update on public.community_comments;
drop policy if exists lawyers_owner_update on public.lawyer_profiles;
drop policy if exists community_posts_owner_insert on public.community_posts;
drop policy if exists community_comments_owner_insert on public.community_comments;
drop policy if exists lawyers_owner_insert on public.lawyer_profiles;

create policy community_posts_owner_insert on public.community_posts
for insert to authenticated with check (user_id=auth.uid() and moderation_status='pending');
create policy community_comments_owner_insert on public.community_comments
for insert to authenticated with check (user_id=auth.uid() and moderation_status='pending');
create policy lawyers_owner_insert on public.lawyer_profiles
for insert to authenticated with check (user_id=auth.uid() and verification_status='pending');

-- Assessments are generated by the authenticated case owner through the API.
create policy assessments_owner_insert on public.case_assessments
for insert to authenticated with check (user_id=auth.uid() and public.owns_case(case_id));

-- Private documents bucket; no public access.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values (
 'case-files','case-files',false,15728640,
 array['application/pdf','image/jpeg','image/png','text/plain',
       'application/msword','application/vnd.openxmlformats-officedocument.wordprocessingml.document']
)
on conflict (id) do update set public=false, file_size_limit=excluded.file_size_limit,
 allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists case_files_owner_read on storage.objects;
drop policy if exists case_files_owner_insert on storage.objects;
create policy case_files_owner_read on storage.objects
for select to authenticated using (
 bucket_id='case-files' and (storage.foldername(name))[1]=auth.uid()::text
);
create policy case_files_owner_insert on storage.objects
for insert to authenticated with check (
 bucket_id='case-files' and (storage.foldername(name))[1]=auth.uid()::text
);
