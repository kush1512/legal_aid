import asyncio
import json
import logging
from dataclasses import dataclass
from typing import Any, Type
from pydantic import BaseModel, ValidationError

from app.config import Settings

logger = logging.getLogger("legal_aid.llm")

class ProviderError(RuntimeError):
    def __init__(self, message: str, *, transient: bool = False):
        super().__init__(message)
        self.transient = transient

@dataclass
class Generation:
    text: str
    provider: str
    model: str
    version: str | None = None
    is_mock: bool = False
    usage: dict[str, int] | None = None

class LLMProvider:
    """Provider adapter contract. Provider SDK details must remain inside adapters."""
    name = "base"
    external = True

    async def generate_text(self, prompt: str, *, model: str, max_tokens: int) -> Generation:
        raise NotImplementedError

    async def generate_structured_output(
        self, prompt: str, *, model: str, max_tokens: int, response_model: Type[BaseModel]
    ) -> tuple[Generation, BaseModel]:
        generation = await self.generate_text(
            prompt + "\\nReturn only valid JSON matching this schema:\\n" +
            json.dumps(response_model.model_json_schema()), model=model, max_tokens=max_tokens
        )
        try:
            parsed = response_model.model_validate_json(generation.text)
        except (ValidationError, ValueError) as exc:
            raise ProviderError("Provider returned invalid structured output", transient=False) from exc
        return generation, parsed

    async def health_check(self) -> bool:
        return True

class MockProvider(LLMProvider):
    name = "mock"
    external = False

    async def generate_text(self, prompt: str, *, model: str, max_tokens: int) -> Generation:
        text = (
            "MOCK AI OUTPUT — not legal advice and not generated by a live model. "
            "This development response is a placeholder for integration testing. "
            "Review the facts, identify missing information, and consult a qualified lawyer."
        )
        return Generation(text=text, provider=self.name, model=model, is_mock=True)

    async def generate_structured_output(
        self, prompt: str, *, model: str, max_tokens: int, response_model: Type[BaseModel]
    ) -> tuple[Generation, BaseModel]:
        payload: dict[str, Any] = {}
        for field_name, field in response_model.model_fields.items():
            annotation = str(field.annotation)
            if field.is_required():
                if "str" in annotation:
                    payload[field_name] = "MOCK — requires real model implementation"
                elif "bool" in annotation:
                    payload[field_name] = False
                elif "int" in annotation or "float" in annotation:
                    payload[field_name] = 0
                elif "list" in annotation:
                    payload[field_name] = []
                elif "dict" in annotation:
                    payload[field_name] = {}
                else:
                    payload[field_name] = None
        try:
            parsed = response_model.model_validate(payload)
        except ValidationError as exc:
            raise ProviderError("Mock schema is not supported by the generic mock adapter") from exc
        return Generation(
            text=parsed.model_dump_json(), provider=self.name, model=model, is_mock=True
        ), parsed

class GeminiProvider(LLMProvider):
    name = "gemini"
    def __init__(self, api_key: str):
        if not api_key:
            raise ProviderError("GEMINI_API_KEY is not configured")
        from google import genai
        self.client = genai.Client(api_key=api_key)

    async def _generate(self, prompt: str, model: str, max_tokens: int, schema: dict | None):
        from google.genai import types
        config = types.GenerateContentConfig(
            temperature=0.2,
            max_output_tokens=max_tokens,
            response_mime_type="application/json" if schema else "text/plain",
            response_schema=schema
        )
        try:
            return await self.client.aio.models.generate_content(
                model=model, contents=prompt, config=config
            )
        except Exception as exc:
            raise _classify_provider_error(exc) from exc

    async def generate_text(self, prompt: str, *, model: str, max_tokens: int) -> Generation:
        result = await self._generate(prompt, model, max_tokens, None)
        return Generation(result.text or "", self.name, model, usage=_usage_from_gemini(result))

    async def generate_structured_output(
        self, prompt: str, *, model: str, max_tokens: int, response_model: Type[BaseModel]
    ) -> tuple[Generation, BaseModel]:
        result = await self._generate(prompt, model, max_tokens, response_model.model_json_schema())
        try:
            parsed = response_model.model_validate_json(result.text or "")
        except (ValidationError, ValueError) as exc:
            raise ProviderError("Gemini returned invalid structured output") from exc
        return Generation(result.text or "", self.name, model, usage=_usage_from_gemini(result)), parsed

    async def health_check(self) -> bool:
        return True

class GroqProvider(LLMProvider):
    name = "groq"
    def __init__(self, api_key: str):
        if not api_key:
            raise ProviderError("GROQ_API_KEY is not configured")
        from groq import AsyncGroq
        self.client = AsyncGroq(api_key=api_key)

    async def _chat(self, prompt: str, model: str, max_tokens: int, json_mode: bool):
        kwargs: dict[str, Any] = {
            "model": model, "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.2, "max_tokens": max_tokens
        }
        if json_mode:
            kwargs["response_format"] = {"type": "json_object"}
        try:
            return await self.client.chat.completions.create(**kwargs)
        except Exception as exc:
            raise _classify_provider_error(exc) from exc

    async def generate_text(self, prompt: str, *, model: str, max_tokens: int) -> Generation:
        result = await self._chat(prompt, model, max_tokens, False)
        choice = result.choices[0]
        return Generation(choice.message.content or "", self.name, model, usage=_usage_from_openai(result))

    async def generate_structured_output(
        self, prompt: str, *, model: str, max_tokens: int, response_model: Type[BaseModel]
    ) -> tuple[Generation, BaseModel]:
        schema_prompt = prompt + "\\nJSON schema:\\n" + json.dumps(response_model.model_json_schema())
        result = await self._chat(schema_prompt, model, max_tokens, True)
        raw = result.choices[0].message.content or ""
        try:
            parsed = response_model.model_validate_json(raw)
        except (ValidationError, ValueError) as exc:
            raise ProviderError("Groq returned invalid structured output") from exc
        return Generation(raw, self.name, model, usage=_usage_from_openai(result)), parsed

class OpenAIProvider(LLMProvider):
    name = "openai"
    def __init__(self, api_key: str):
        if not api_key:
            raise ProviderError("OPENAI_API_KEY is not configured")
        from openai import AsyncOpenAI
        self.client = AsyncOpenAI(api_key=api_key)

    async def generate_text(self, prompt: str, *, model: str, max_tokens: int) -> Generation:
        try:
            result = await self.client.chat.completions.create(
                model=model, messages=[{"role": "user", "content": prompt}],
                max_tokens=max_tokens, temperature=0.2
            )
        except Exception as exc:
            raise _classify_provider_error(exc) from exc
        return Generation(result.choices[0].message.content or "", self.name, model, usage=_usage_from_openai(result))

    async def generate_structured_output(
        self, prompt: str, *, model: str, max_tokens: int, response_model: Type[BaseModel]
    ) -> tuple[Generation, BaseModel]:
        try:
            result = await self.client.chat.completions.create(
                model=model, messages=[{"role": "user", "content": prompt}],
                max_tokens=max_tokens, temperature=0.1, response_format={"type": "json_object"}
            )
        except Exception as exc:
            raise _classify_provider_error(exc) from exc
        raw = result.choices[0].message.content or ""
        try:
            parsed = response_model.model_validate_json(raw)
        except (ValidationError, ValueError) as exc:
            raise ProviderError("OpenAI returned invalid structured output") from exc
        return Generation(raw, self.name, model, usage=_usage_from_openai(result)), parsed

class AnthropicProvider(LLMProvider):
    name = "anthropic"
    def __init__(self, api_key: str):
        if not api_key:
            raise ProviderError("ANTHROPIC_API_KEY is not configured")
        from anthropic import AsyncAnthropic
        self.client = AsyncAnthropic(api_key=api_key)

    async def generate_text(self, prompt: str, *, model: str, max_tokens: int) -> Generation:
        try:
            result = await self.client.messages.create(
                model=model, max_tokens=max_tokens, temperature=0.2,
                messages=[{"role": "user", "content": prompt}]
            )
        except Exception as exc:
            raise _classify_provider_error(exc) from exc
        text = "".join(block.text for block in result.content if getattr(block, "type", "") == "text")
        usage = {"input_tokens": result.usage.input_tokens, "output_tokens": result.usage.output_tokens}
        return Generation(text, self.name, model, usage=usage)

def _usage_from_openai(result: Any) -> dict[str, int] | None:
    usage = getattr(result, "usage", None)
    if not usage:
        return None
    return {"input_tokens": usage.prompt_tokens, "output_tokens": usage.completion_tokens}

def _usage_from_gemini(result: Any) -> dict[str, int] | None:
    usage = getattr(result, "usage_metadata", None)
    if not usage:
        return None
    return {
        "input_tokens": int(getattr(usage, "prompt_token_count", 0) or 0),
        "output_tokens": int(getattr(usage, "candidates_token_count", 0) or 0)
    }

def _classify_provider_error(exc: Exception) -> ProviderError:
    status = getattr(exc, "status_code", None) or getattr(exc, "code", None)
    text = str(exc).lower()
    transient = status in (408, 409, 429, 500, 502, 503, 504) or any(
        key in text for key in ("timeout", "temporarily unavailable", "connection reset", "rate limit", "429")
    )
    return ProviderError("LLM provider request failed", transient=transient)

class LLMOrchestrator:
    def __init__(self, settings: Settings):
        self.settings = settings

    def _provider(self, name: str) -> LLMProvider:
        providers = {
            "mock": lambda: MockProvider(),
            "gemini": lambda: GeminiProvider(self.settings.gemini_api_key),
            "groq": lambda: GroqProvider(self.settings.groq_api_key),
            "openai": lambda: OpenAIProvider(self.settings.openai_api_key),
            "anthropic": lambda: AnthropicProvider(self.settings.anthropic_api_key),
        }
        if name not in providers:
            raise ProviderError(f"Unsupported LLM provider: {name}")
        return providers[name]()

    def _privacy_check(self, provider: LLMProvider, *, sensitive: bool, user_consent: bool):
        if provider.external and sensitive:
            allowed = self.settings.allow_external_llm_for_sensitive and user_consent
            if not allowed:
                raise ProviderError("External AI processing blocked by privacy policy", transient=False)

    async def _invoke(self, operation, *, provider_name: str, model: str, sensitive: bool, user_consent: bool):
        if provider_name != "mock" and sensitive:
            allowed = self.settings.allow_external_llm_for_sensitive and user_consent
            if not allowed:
                raise ProviderError("External AI processing blocked by privacy policy", transient=False)
        provider = self._provider(provider_name)
        self._privacy_check(provider, sensitive=sensitive, user_consent=user_consent)
        last_error: ProviderError | None = None
        for attempt in range(max(0, self.settings.llm_max_retries) + 1):
            try:
                result = await asyncio.wait_for(
                    operation(provider, model), timeout=self.settings.llm_timeout_seconds
                )
                generation=result[0] if isinstance(result,tuple) else result
                usage=generation.usage or {}
                logger.info(
                    "llm_response provider=%s model=%s mock=%s input_tokens=%s output_tokens=%s",
                    provider_name,model,generation.is_mock,
                    usage.get("input_tokens"),usage.get("output_tokens")
                )
                return result
            except asyncio.TimeoutError as exc:
                last_error = ProviderError("LLM provider timed out", transient=True)
            except ProviderError as exc:
                last_error = exc
            if not last_error.transient or attempt >= self.settings.llm_max_retries:
                break
            await asyncio.sleep(min(2 ** attempt, 4))
        raise last_error or ProviderError("LLM provider unavailable", transient=True)

    async def generate_text(self, prompt: str, *, sensitive: bool = False, user_consent: bool = False,
                            model: str | None = None):
        primary = self.settings.llm_provider
        selected_model = model or self.settings.llm_model
        try:
            return await self._invoke(
                lambda p, m: p.generate_text(prompt, model=m, max_tokens=self.settings.llm_max_output_tokens),
                provider_name=primary, model=selected_model, sensitive=sensitive, user_consent=user_consent
            )
        except ProviderError as exc:
            if not (exc.transient and self.settings.llm_fallback_enabled and self.settings.fallback_llm_provider):
                raise
            fallback = self.settings.fallback_llm_provider
            # Re-run privacy checks independently. Sensitive payloads never move providers silently.
            return await self._invoke(
                lambda p, m: p.generate_text(prompt, model=m, max_tokens=self.settings.llm_max_output_tokens),
                provider_name=fallback, model=self.settings.fallback_llm_model or selected_model,
                sensitive=sensitive, user_consent=user_consent
            )

    async def generate_structured_output(self, prompt: str, response_model: Type[BaseModel], *,
                                         sensitive: bool = False, user_consent: bool = False,
                                         model: str | None = None):
        primary = self.settings.llm_provider
        selected_model = model or self.settings.llm_model
        try:
            return await self._invoke(
                lambda p, m: p.generate_structured_output(
                    prompt, model=m, max_tokens=self.settings.llm_max_output_tokens,
                    response_model=response_model
                ),
                provider_name=primary, model=selected_model, sensitive=sensitive, user_consent=user_consent
            )
        except ProviderError as exc:
            if not (exc.transient and self.settings.llm_fallback_enabled and self.settings.fallback_llm_provider):
                raise
            fallback = self.settings.fallback_llm_provider
            return await self._invoke(
                lambda p, m: p.generate_structured_output(
                    prompt, model=m, max_tokens=self.settings.llm_max_output_tokens,
                    response_model=response_model
                ),
                provider_name=fallback, model=self.settings.fallback_llm_model or selected_model,
                sensitive=sensitive, user_consent=user_consent
            )
